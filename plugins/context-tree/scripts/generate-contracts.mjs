import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import ts from "typescript";

const contractFile = join(process.cwd(), "src", "protocol", "contracts.ts");
const outputFile = join(process.cwd(), "src", "protocol", "generated", "contracts-metadata.ts");

const program = ts.createProgram([contractFile], {
  target: ts.ScriptTarget.ES2022,
  module: ts.ModuleKind.NodeNext,
  moduleResolution: ts.ModuleResolutionKind.NodeNext,
  strict: true,
});
const sourceFile = program.getSourceFile(contractFile);

if (!sourceFile) {
  throw new Error("unable to load source contracts");
}

const declarations = new Map();

for (const statement of sourceFile.statements) {
  if (!isExported(statement)) {
    continue;
  }

  if (
    ts.isInterfaceDeclaration(statement) ||
    ts.isTypeAliasDeclaration(statement)
  ) {
    declarations.set(statement.name.text, statement);
  }
}

const schemas = {};

for (const [name, declaration] of declarations) {
  if (hasTag(declaration, "schema")) {
    schemas[name] = describeDeclaration(declaration);
  }
}

const metadata = {
  version: 5,
  schemas,
};

await mkdir(dirname(outputFile), { recursive: true });
await writeFile(
  outputFile,
  [
    "/* This file is generated by scripts/generate-contracts.mjs. */",
    "import type { ContractMetadata } from \"../contract-metadata.js\";",
    "",
    "export const contractMetadata = " + JSON.stringify(metadata, null, 2) +
      " as const satisfies ContractMetadata;",
    "",
  ].join("\n"),
);

function describeDeclaration(declaration) {
  if (ts.isInterfaceDeclaration(declaration)) {
    return describeInterface(declaration);
  }

  return {
    ...describeType(declaration.type),
    ...constraints(declaration),
  };
}

function describeInterface(declaration) {
  const properties = {};

  for (const member of declaration.members) {
    if (!ts.isPropertySignature(member) || !member.name || !member.type) {
      continue;
    }

    if (!ts.isIdentifier(member.name) && !ts.isStringLiteral(member.name)) {
      throw new Error("unsupported property name in " + declaration.name.text);
    }

    const name = member.name.text;
    properties[name] = {
      ...describeType(member.type),
      optional: Boolean(member.questionToken),
      ...constraints(member),
    };
  }

  const extendsNames = [];

  for (const clause of declaration.heritageClauses ?? []) {
    if (clause.token !== ts.SyntaxKind.ExtendsKeyword) {
      continue;
    }

    for (const type of clause.types) {
      extendsNames.push(type.expression.getText(sourceFile));
    }
  }

  return {
    kind: "object",
    strict: hasTag(declaration, "strict"),
    extends: extendsNames,
    properties,
  };
}

function describeType(node) {
  if (node.kind === ts.SyntaxKind.StringKeyword) {
    return { kind: "string" };
  }

  if (node.kind === ts.SyntaxKind.NumberKeyword) {
    return { kind: "number" };
  }

  if (node.kind === ts.SyntaxKind.BooleanKeyword) {
    return { kind: "boolean" };
  }

  if (node.kind === ts.SyntaxKind.NullKeyword) {
    return { kind: "null" };
  }

  if (node.kind === ts.SyntaxKind.UnknownKeyword) {
    return { kind: "unknown" };
  }

  if (node.kind === ts.SyntaxKind.NeverKeyword) {
    return { kind: "never" };
  }

  if (ts.isLiteralTypeNode(node)) {
    return {
      kind: "literal",
      value: literalValue(node.literal),
    };
  }

  if (ts.isUnionTypeNode(node)) {
    return {
      kind: "union",
      options: node.types.map((member) => describeType(member)),
    };
  }

  if (ts.isArrayTypeNode(node)) {
    return {
      kind: "array",
      element: describeType(node.elementType),
    };
  }

  if (ts.isParenthesizedTypeNode(node)) {
    return describeType(node.type);
  }

  if (ts.isTypeOperatorNode(node) && node.operator === ts.SyntaxKind.KeyOfKeyword) {
    if (!ts.isTypeReferenceNode(node.type)) {
      throw new Error("keyof contracts must target a named declaration");
    }

    const targetName = node.type.typeName.getText(sourceFile);
    const target = declarations.get(targetName);

    if (!target || !ts.isInterfaceDeclaration(target)) {
      throw new Error("keyof target is not an interface: " + targetName);
    }

    return {
      kind: "union",
      options: target.members
        .filter((member) => ts.isPropertySignature(member) && member.name)
        .map((member) => ({
          kind: "literal",
          value: propertyName(member.name),
        })),
    };
  }

  if (ts.isTypeLiteralNode(node)) {
    return describeAnonymousObject(node);
  }

  if (ts.isTypeReferenceNode(node)) {
    const name = node.typeName.getText(sourceFile);
    const arguments_ = node.typeArguments ?? [];

    if (name === "Array" && arguments_.length === 1) {
      return {
        kind: "array",
        element: describeType(arguments_[0]),
      };
    }

    if (name === "Record" && arguments_.length === 2) {
      return {
        kind: "record",
        value: describeType(arguments_[1]),
      };
    }

    if (name === "Partial" && arguments_.length === 1) {
      return {
        kind: "partial",
        target: describeType(arguments_[0]),
      };
    }

    return {
      kind: "ref",
      name,
    };
  }

  throw new Error(
    "unsupported contract type syntax: " + ts.SyntaxKind[node.kind],
  );
}

function describeAnonymousObject(node) {
  const indexSignature = node.members.find((member) =>
    ts.isIndexSignatureDeclaration(member),
  );

  if (indexSignature?.type) {
    if (node.members.length !== 1) {
      throw new Error("index-signature objects cannot mix named properties");
    }

    return {
      kind: "record",
      value: describeType(indexSignature.type),
    };
  }

  const properties = {};

  for (const member of node.members) {
    if (
      !ts.isPropertySignature(member) ||
      !member.name ||
      !member.type ||
      (!ts.isIdentifier(member.name) && !ts.isStringLiteral(member.name))
    ) {
      throw new Error("unsupported anonymous object member");
    }

    properties[member.name.text] = {
      ...describeType(member.type),
      optional: Boolean(member.questionToken),
      ...constraints(member),
    };
  }

  return {
    kind: "object",
    strict: true,
    extends: [],
    properties,
  };
}

function constraints(node) {
  const metadata = {};
  const minLength = tagValue(node, "minLength");
  const minItems = tagValue(node, "minItems");
  const defaultValue = tagValue(node, "default");

  if (minLength) {
    metadata.minLength = Number(minLength);
  }

  if (minItems) {
    metadata.minItems = Number(minItems);
  }

  if (hasTag(node, "uuid")) {
    metadata.format = "uuid";
  }

  if (hasTag(node, "datetime")) {
    metadata.format = "datetime";
  }

  if (hasTag(node, "int")) {
    metadata.integer = true;
  }

  if (hasTag(node, "nonnegative")) {
    metadata.nonnegative = true;
  }

  if (hasTag(node, "positive")) {
    metadata.positive = true;
  }

  if (defaultValue !== undefined) {
    metadata.default = parseDefault(defaultValue);
  }

  return metadata;
}

function hasTag(node, name) {
  return new RegExp("@" + name + "(?:\\s|\\*|$)").test(
    node.getFullText(sourceFile),
  );
}

function tagValue(node, name) {
  const match = node.getFullText(sourceFile).match(
    new RegExp("@" + name + "\\s+([^\\s*]+)"),
  );

  return match?.[1]?.trim();
}

function parseDefault(raw) {
  if (raw === "true") {
    return true;
  }

  if (raw === "false") {
    return false;
  }

  if (raw === "null") {
    return null;
  }

  if (raw === "[]") {
    return [];
  }

  if (raw === "{}") {
    return {};
  }

  if (/^-?\\d+(\\.\\d+)?$/.test(raw)) {
    return Number(raw);
  }

  return raw.replace(/^["']|["']$/g, "");
}

function literalValue(node) {
  if (ts.isStringLiteral(node)) {
    return node.text;
  }

  if (ts.isNumericLiteral(node)) {
    return Number(node.text);
  }

  if (node.kind === ts.SyntaxKind.TrueKeyword) {
    return true;
  }

  if (node.kind === ts.SyntaxKind.FalseKeyword) {
    return false;
  }

  if (node.kind === ts.SyntaxKind.NullKeyword) {
    return null;
  }

  throw new Error("unsupported literal type");
}

function propertyName(node) {
  if (ts.isIdentifier(node) || ts.isStringLiteral(node)) {
    return node.text;
  }

  throw new Error("unsupported property name");
}

function isExported(node) {
  return Boolean(
    ts.getCombinedModifierFlags(node) & ts.ModifierFlags.Export,
  );
}
